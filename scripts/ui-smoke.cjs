const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const puppeteer = require('../.hallmark/tools/node_modules/puppeteer-core');

const url = process.env.APP_URL || 'http://127.0.0.1:8000';
const output = path.join(__dirname, '..', '.hallmark', 'screens');
fs.mkdirSync(output, { recursive: true });
let runningBrowser;

(async () => {
  const browser = await puppeteer.launch({ executablePath: process.env.CHROME_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true, args: ['--no-sandbox'] });
  runningBrowser = browser;
  const errors = [];
  const page = await browser.newPage();
  page.on('pageerror', error => errors.push(error.message));
  await page.setBypassServiceWorker(true);
  await page.setRequestInterception(true);
  page.on('request', request => {
    const address = request.url();
    const respond = json => request.respond({ status: 200, headers: { 'Access-Control-Allow-Origin': '*' }, contentType: 'application/json', body: JSON.stringify(json) });
    if (address.includes('api.tomtom.com')) return respond({ results: [
      { id: 'bell-test', poi: { name: 'Bell Artisan Cafe', categories: ['Cafe'] }, position: { lat: 2.8289, lon: 101.7069 }, address: { freeformAddress: 'Bell Avenue, Sunsuria City' } },
      { id: 'warisan-test', poi: { name: 'Mohd Chan Restaurant', categories: ['Restaurant'] }, position: { lat: 2.8215, lon: 101.7010 }, address: { freeformAddress: 'Jalan Warisan Sentral 1, Kota Warisan' } },
    ] });
    if (address.includes('overpass')) return respond({ elements: [] });
    if (address.includes('nominatim')) return respond([{ lat: '2.8289', lon: '101.7069', display_name: 'Sunsuria City, Sepang' }]);
    return request.continue();
  });
  await page.setViewport({ width: 1440, height: 900 });
  await page.goto(url, { waitUntil: 'networkidle2' });
  await page.waitForSelector('#spinBtn:disabled');
  await page.screenshot({ path: path.join(output, 'desktop-empty.png'), fullPage: true });
  await page.click('[data-tab="favourites"]');
  await page.waitForSelector('#tab-favourites:not([hidden])');
  await page.click('#addFavBtn');
  await page.waitForSelector('#favDialog[open]');
  await page.type('#favForm [name="name"]', 'Bell Artisan Cafe');
  await page.type('#favForm [name="cuisine"]', 'Cafe');
  await page.type('#favForm [name="address"]', 'Bell Avenue, Sunsuria City');
  await page.select('#favForm [name="price"]', '2');
  await page.click('#favForm button[type="submit"]');
  await page.waitForSelector('#favDialog:not([open])');
  assert.match(await page.$eval('#favList', element => element.textContent), /Bell Artisan Cafe/);
  await page.click('#addFavBtn');
  await page.type('#favForm [name="name"]', 'AllAce');
  await page.type('#favForm [name="cuisine"]', 'Burgers');
  await page.click('#favForm button[type="submit"]');
  await page.waitForSelector('#favDialog:not([open])');
  await page.click('[data-tab="decide"]');
  await page.waitForSelector('#spinBtn:not(:disabled)');
  await page.screenshot({ path: path.join(output, 'desktop-decide.png'), fullPage: true });
  await page.click('#spinBtn');
  await page.waitForSelector('#result.done');
  assert.match(await page.$eval('#result .name', element => element.textContent), /AllAce|Bell Artisan Cafe/);
  await page.click('#result [data-action="pick-this"]');
  await page.click('[data-tab="history"]');
  await page.waitForSelector('#historyList [data-action="delete-history"]');
  assert.match(await page.$eval('#stats', element => element.textContent), /1/);
  await page.click('#logMealBtn');
  await page.waitForSelector('#logDialog[open]');
  await page.type('#logForm [name="name"]', 'SOI 55 Thai Kitchen');
  await page.click('#logForm button[type="submit"]');
  await page.waitForSelector('#logDialog:not([open])');
  assert.equal(await page.$$eval('#historyList .h-name', elements => elements.length), 2);
  await page.click('[data-tab="decide"]');
  await page.click('#threeBtn');
  await page.waitForSelector('#choices:not([hidden]) .place');
  assert.equal(await page.$$eval('#choices .place', elements => elements.length), 2);
  await page.click('#decideFilters summary');
  await page.select('#fCuisine', 'Burgers');
  assert.match(await page.$eval('#poolInfo', element => element.textContent), /1.*2/);
  await page.select('#fCuisine', '');
  await page.click('#decideFilters summary');
  await page.click('[data-tab="nearby"]');
  await page.waitForSelector('#tab-nearby:not([hidden])');
  await page.type('#placeQuery', 'Sunsuria City');
  await page.click('#placeSearch button');
  await page.waitForSelector('#placeResults button[data-i]', { visible: true });
  await page.click('#placeResults button[data-i]');
  await page.waitForSelector('#nearbyList .place');
  assert.equal(await page.$$eval('#nearbyList .place', elements => elements.length), 2);
  await page.click('#nearbyList .star-btn');
  assert.equal(await page.$$eval('#nearbyList .is-saved', elements => elements.length), 1);
  await page.click('#xmumBtn');
  await page.waitForFunction(() => document.querySelector('#xmumBtn').getAttribute('aria-pressed') === 'true');
  await page.click('[data-tab="xmum"]');
  await page.waitForSelector('#xmumAreaSeg [data-area="sunsuria"]');
  await page.click('#xmumAreaSeg [data-area="sunsuria"]');
  await page.waitForSelector('#xmumList .place');
  await page.screenshot({ path: path.join(output, 'desktop-xmum.png'), fullPage: true });
  await page.click('#xmumAreaSeg [data-area="warisan"]');
  await page.waitForFunction(() => document.querySelector('#xmumList').textContent.includes('Mohd Chan'));
  await page.click('#settingsBtn');
  await page.waitForSelector('#settingsDialog[open]');
  await page.select('#themeSel', 'light');
  assert.equal(await page.$eval('html', element => element.dataset.theme), 'light');
  await page.screenshot({ path: path.join(output, 'desktop-light-settings.png'), fullPage: true });
  await page.select('#themeSel', 'dark');
  await page.click('#settingsDialog button[value="close"]');
  await page.click('[data-tab="decide"]');
  await page.click('#spinBtn');
  await page.waitForSelector('#result.done');
  for (const width of [320, 375, 390, 768, 1280, 1440, 1920]) {
    await page.setViewport({ width, height: width < 760 ? 844 : 900 });
    const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth);
    assert.equal(overflow, false, `Horizontal overflow at ${width}px`);
    await page.screenshot({ path: path.join(output, `decide-${width}.png`), fullPage: true });
  }
  await page.setViewport({ width: 390, height: 844 });
  await page.click('[data-tab="favourites"]');
  await page.waitForSelector('#tab-favourites:not([hidden])');
  await page.screenshot({ path: path.join(output, 'phone-places.png'), fullPage: true });
  await page.click('#favList [data-action="edit-fav"]');
  await page.waitForSelector('#favDialog[open]');
  await page.screenshot({ path: path.join(output, 'phone-edit.png'), fullPage: true });
  await page.keyboard.press('Escape');
  assert.equal(await page.$eval('#favDialog', element => element.open), false);
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }]);
  assert(await page.$eval('.tab', element => parseFloat(getComputedStyle(element).transitionDuration) <= .001));
  await page.keyboard.press('Tab');
  assert(await page.evaluate(() => document.activeElement.matches(':focus-visible')));
  await page.reload({ waitUntil: 'networkidle2' });
  assert.equal(await page.evaluate(() => JSON.parse(localStorage.getItem('w2e.v1')).favourites.length), 3);
  assert.deepEqual(errors, []);
  console.log('PASS: saved-place creation, picking, meal logging, three choices, filters, area search, saving, XMUM areas, theme switching, mobile layout, dialog dismissal, reduced motion, keyboard focus, persistence, and no page errors.');
  await browser.close();
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(() => runningBrowser?.close());
